// Illustrative events for demonstrations. They are published but clearly
// labelled as samples in their title and source label; replace them from the
// academic calendar (public listing only shows verified rows).
const day = 24 * 3600000;
const soon = (days: number, hour: number) => {
  const d = new Date();
  d.setUTCHours(hour - 1, 0, 0, 0); // WAT is UTC+1
  return new Date(d.getTime() + days * day);
};
